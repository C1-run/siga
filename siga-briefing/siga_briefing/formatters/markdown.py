"""Markdown formatter for Morning Operational Briefing."""
from datetime import datetime


def _section(title: str, body: str) -> str:
    return f"\n## {title}\n\n{body}\n"


def _kv(label: str, value: str) -> str:
    return f"- **{label}:** {value}\n"


def render(report: dict) -> str:
    """Render briefing dict to Markdown string."""
    lines = [
        "# Morning Operational Briefing",
        "",
        f"**Generated:** {report.get('generated_at', 'N/A')}",
        f"**Symbol:** {report.get('symbol', 'N/A')}",
        f"**Lookback:** {report.get('lookback_hours', 24)}h",
        "---",
    ]

    ext = report.get("external", {})
    if ext and not ext.get("error"):
        sol_price = ext.get("sol_price")
        sol_chg = ext.get("sol_24h_change_pct")
        fgi = ext.get("fear_greed_index")
        fgl = ext.get("fear_greed_label")
        price_str = f"${sol_price:,.2f}" if sol_price else "N/A"
        chg_str = f"{sol_chg:+.2f}%" if sol_chg is not None else "N/A"
        fg_str = f"{fgi} ({fgl})" if fgi else "N/A"
        sol_7d = ext.get("sol_7d_change_pct")
        sol_7d_str = f"{sol_7d:+.2f}%" if sol_7d is not None else "N/A"
        lines.append(_section("Market Context", (
            _kv("SOL Price", price_str) +
            _kv("24h Change", chg_str) +
            _kv("Fear & Greed", fg_str) +
            _kv("7d Momentum", sol_7d_str)
        )))

    arena = report.get("arena", {})
    if arena:
        if arena.get("error"):
            lines.append(_section("Arena v3 Report", _kv("Status", f"Unavailable ({arena['error']})")))
        else:
            lines.append(_section("Arena v3 Report", (
                _kv("Total Bets", arena.get("total_bets", 0)) +
                _kv("Win Rate", f"{arena.get('win_rate', 0)*100:.1f}%") +
                _kv("Total PnL", f"${arena.get('total_pnl', 0):+.2f}")
            )))

    paper = report.get("paper", {})
    if paper:
        if paper.get("error"):
            lines.append(_section("Paper Trading", _kv("Status", f"Unavailable ({paper['error']})")))
        else:
            lines.append(_section("Paper Trading", (
                _kv("Signals Generated", paper.get("signals_generated", 0)) +
                _kv("Trades Taken", paper.get("trades_taken", 0)) +
                _kv("Win Rate", f"{paper.get('win_rate', 0)*100:.1f}%") +
                _kv("Total PnL", f"${paper.get('total_pnl', 0):+.2f}")
            )))

    soak = report.get("soak", {})
    if soak:
        if soak.get("error"):
            lines.append(_section("Soak Testing", _kv("Status", f"Unavailable ({soak['error']})")))
        else:
            lines.append(_section("Soak Testing", (
                _kv("Status", soak.get("status", "unknown")) +
                _kv("Avg Cycle Time", f"{soak.get('avg_cycle_ms', 'N/A')}ms" if soak.get("avg_cycle_ms") else "N/A") +
                _kv("Trend", soak.get("trend", "N/A"))
            )))

    tomb = report.get("tomb", {})
    if tomb and not tomb.get("error"):
        oi = tomb.get("open_interest")
        lines.append(_section("Tomb Cluster", (
            _kv("Open Interest", f"${oi.get('total', 0):,.0f}" if oi else "N/A") +
            _kv("Support Levels", ", ".join(f"${s:,.2f}" for s in tomb.get("support_clusters", [])) or "N/A") +
            _kv("Resistance Levels", ", ".join(f"${s:,.2f}" for s in tomb.get("resistance_clusters", [])) or "N/A")
        )))

    lines.append(_section("Verdict", _verdict(report)))
    lines.append("\n---\n*Auto-generated by siga-briefing*\n")
    return "\n".join(lines)


def _verdict(report: dict) -> str:
    parts = []
    ext = report.get("external", {})
    if ext and not ext.get("error"):
        fg = ext.get("fear_greed_index")
        fgl = ext.get("fear_greed_label")
        if fg:
            parts.append(f"Market sentiment: {fgl} (FG={fg}).")
    tomb = report.get("tomb", {})
    if tomb and not tomb.get("error"):
        supports = tomb.get("support_clusters", [])
        resistances = tomb.get("resistance_clusters", [])
        if supports or resistances:
            s = f"support at ${supports[0]:,.2f}" if supports else ""
            r = f"resistance at ${resistances[0]:,.2f}" if resistances else ""
            levels = ", ".join(x for x in [s, r] if x)
            if levels:
                parts.append(f"Key levels: {levels}.")
    return " ".join(parts) if parts else "No significant signals detected."


