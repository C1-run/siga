def _sign_prefix(val: float) -> str:
    """Format a dollar amount with sign prefix: +$1,234 or -$1,234."""
    return f"+${val:,.2f}" if val >= 0 else f"-${abs(val):,.2f}"


def render_portfolio(report: dict) -> str:
    """Render portfolio-aware briefing to Markdown string.

    Format: table overview + detail blocks for holdings with risk flags.
    """
    gen = report.get("generated_at", "N/A")
    try:
        dt = datetime.fromisoformat(gen)
        gen_str = dt.strftime("%Y-%m-%d %H:%M")
    except (TypeError, ValueError):
        gen_str = gen

    lines = [
        f"# Brief — {gen_str}",
        "",
    ]

    ctx = report.get("portfolio", {})
    holdings = ctx.get("holdings", [])
    total = ctx.get("total", {})

    # Fear & Greed
    fg = ctx.get("fear_greed")
    if fg and fg.get("value") is not None:
        lines.append(f"**Market:** Fear & Greed {fg['value']} ({fg.get('value_classification', 'N/A')})")
        lines.append("")

    # Total summary
    if total:
        cost = total.get("cost", 0)
        value = total.get("value", 0)
        pnl = total.get("pnl", 0)
        pnl_pct = total.get("pnl_pct", 0)
        lines.append(
            f"**Total:** ${value:,.2f}  "
            f"(cost ${cost:,.2f}, P&L {_sign_prefix(pnl)} / {pnl_pct:+.1f}%)"
        )
        lines.append("")

    # Holdings table
    if holdings:
        lines.append(_section("Holdings", _holdings_table(holdings)))

    # Detail blocks for holdings with flags
    flagged = [h for h in holdings if h.get("flags")]
    if flagged:
        lines.append(_section("Attention", _flagged_details(flagged)))

    lines.append("\n---\n*Auto-generated by siga. Not investment advice.*\n")
    return "\n".join(lines)


def _holdings_table(holdings: list[dict]) -> str:
    header = "| Symbol | Price | 24h | 7d | P&L | P&L% | Wt% |"
    sep = "|---|---|---|---|---|---|---|"
    lines = [header, sep]
    for h in holdings:
        price_str = f"${h['current_price']:,.2f}" if h["current_price"] else "\u2014"
        chg24 = h.get("change_24h")
        chg7d = h.get("change_7d")
        chg24_str = f"{chg24:+.1f}%" if chg24 is not None else "\u2014"
        chg7d_str = f"{chg7d:+.1f}%" if chg7d is not None else "\u2014"
        pnl = h.get("pnl", 0)
        pnl_pct = h.get("pnl_pct", 0)
        alloc = h.get("allocation", 0)
        lines.append(
            f"| {h['symbol']} | {price_str} | {chg24_str} | {chg7d_str} "
            f"| {_sign_prefix(pnl)} | {pnl_pct:+.1f}% | {alloc:.1f}% |"
        )
    return "\n".join(lines)


def _flagged_details(holdings: list[dict]) -> str:
    """Render detail blocks for holdings with risk flags."""
    parts = []
    for h in holdings:
        sym = h["symbol"]
        price = h.get("current_price", 0)
        qty = h.get("quantity", 0)
        value = h.get("value", 0)
        pnl = h.get("pnl", 0)
        pnl_pct = h.get("pnl_pct", 0)
        alloc = h.get("allocation", 0)
        chg24 = h.get("change_24h")
        chg7d = h.get("change_7d")
        flags = h.get("flags", [])

        price_str = f"${price:,.2f}" if price else "\u2014"
        chg24_str = f"{chg24:+.1f}%" if chg24 is not None else "N/A"
        chg7d_str = f"{chg7d:+.1f}%" if chg7d is not None else "N/A"

        parts.append(f"### {sym} \u2014 {alloc:.1f}% of portfolio")
        parts.append(f"- Price: {price_str}  (24h {chg24_str}, 7d {chg7d_str})")
        parts.append(
            f"- Position: {qty} {sym} = ${value:,.2f}  "
            f"(P&L {_sign_prefix(pnl)} / {pnl_pct:+.1f}%)"
        )
        if flags:
            parts.append(f"- Flags: {'; '.join(flags)}")
        parts.append("")

    return "\n".join(parts)
